# Decodificar a un ZIP temporal
$tmpZip = Join-Path $env:TEMP ("bs_deploy_" + [guid]::NewGuid().ToString().Substring(0,8) + ".zip")
[IO.File]::WriteAllBytes($tmpZip, [Convert]::FromBase64String(($b64 -replace '\s','')))

# Extraer
$extractDir = Join-Path $env:TEMP ("bs_deploy_" + [guid]::NewGuid().ToString().Substring(0,8))
Expand-Archive -Path $tmpZip -DestinationPath $extractDir -Force
Remove-Item $tmpZip

Write-Host ""
Write-Host "===== Deploy Fase 1+2 — Backend del Registry =====" -ForegroundColor Cyan
Write-Host "Subiendo archivos..." -ForegroundColor Cyan

# Subir api/*
foreach ($f in (Get-ChildItem (Join-Path $extractDir "api") -File)) {
    $fname = $f.Name
    $remoteName = if ($fname -eq '_dot_htaccess') { '.htaccess' } else { $fname }
    $remotePath = "$($env:FTP_REMOTE_BASE)/calculadora/api/$remoteName"
    curl.exe --user "${env:FTP_USER}:${env:FTP_PASS}" -s -T $f.FullName "ftp://${env:FTP_HOST}/$remotePath"
    if ($LASTEXITCODE -eq 0) {
        Write-Host "  OK calculadora/api/$remoteName" -ForegroundColor Green
    } else {
        Write-Host "  FALLO calculadora/api/$remoteName (curl $LASTEXITCODE)" -ForegroundColor Red
    }
}

# Subir presupuestos/*
foreach ($f in (Get-ChildItem (Join-Path $extractDir "presupuestos") -File)) {
    $fname = $f.Name
    $remotePath = "$($env:FTP_REMOTE_BASE)/presupuestos/$fname"
    curl.exe --user "${env:FTP_USER}:${env:FTP_PASS}" -s -T $f.FullName "ftp://${env:FTP_HOST}/$remotePath"
    if ($LASTEXITCODE -eq 0) {
        Write-Host "  OK presupuestos/$fname" -ForegroundColor Green
    } else {
        Write-Host "  FALLO presupuestos/$fname (curl $LASTEXITCODE)" -ForegroundColor Red
    }
}

Remove-Item -Recurse -Force $extractDir

